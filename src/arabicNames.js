const NOISE = new Set(['fc', 'cf', 'ac', 'afc', 'sc', 'ssc', 'as', 'ud', 'cd', 'fk', 'sk', 'the']);

const normalize = (name) =>
  name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9 ]+/g, ' ')
    .split(/\s+/)
    .filter((w) => w && !NOISE.has(w))
    .join(' ');

/** Arabic name for a team, or the original name when we don't have one. */
export const arabicName = (name) => NAMES[normalize(name)] ?? name;
